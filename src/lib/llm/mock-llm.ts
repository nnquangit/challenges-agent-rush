// MockLlm — deterministic planner/explainer. No network, no model. Returns plan
// JSON shaped exactly like what VultrInferenceLlm will be asked to produce.

import { extractCsv, parseCsv } from "../csv";
import { newId, now } from "../ids";
import type { Intent, Plan, PlanStep, Receipt } from "../types";
import type { LlmProvider, PlanInput, Repair } from "./provider";

export function classifyIntent(message: string): Intent {
  if (extractCsv(message) || /\bcsv\b/i.test(message)) return "csv";
  if (/https?:\/\/|\bbrows(e|er)\b|\bwebsite\b|\bweb ?page\b|\bscreenshot\b|\bopen (the )?(page|site)\b/i.test(message)) return "browser";
  return "code";
}

const step = (n: number, s: Omit<PlanStep, "id">): PlanStep => ({ id: `s${n}`, ...s });

// ---------- code ----------

// Probes are not planned here: src/lib/policy.ts inserts them for every provider.

function extractPython(message: string): string | null {
  return message.match(/```(?:python|py)?\n([\s\S]*?)```/)?.[1]?.trimEnd() ?? null;
}

function codePlan(message: string): Omit<Plan, "id" | "createdAt" | "planner"> {
  const user = extractPython(message);
  const expr = message.match(/(?:compute|calculate|what is)\s+([\d\s+\-*/().%]+)/i)?.[1]?.trim();
  const code = user ?? (expr ? `print(${expr})` : `# Draft generated by MockLlm for: ${message.slice(0, 80)}\nprint("hello from the sandbox")`);
  return {
    intent: "code",
    title: user ? "Prove the snippet in a sandbox" : "Run generated code in a sandbox",
    summary: "Run the code in a fresh sandbox, then prove the sandbox cannot reach secrets, the host, or exceed its resource caps.",
    steps: [
      step(1, { kind: "code", language: "python", title: "Run code in sandbox", description: "Execute the snippet; capture stdout, stderr, exit code and artifacts.", code }),
    ],
  };
}

// ---------- csv ----------

const VALUE_WORDS = ["revenue", "sales", "amount", "units", "price", "total", "profit", "cost"];

function csvPlan(message: string): Omit<Plan, "id" | "createdAt" | "planner"> {
  const csv = extractCsv(message) ?? "a,b\n1,2\n3,4";
  const { columns, rows } = parseCsv(csv);
  // Read intent words from the instruction only, not from the pasted data.
  const lower = message.replace(/```[\s\S]*?```/g, " ").replace(csv, " ").toLowerCase();
  const numeric = columns.filter((_, i) => rows.every((r) => r[i] === "" || Number.isFinite(Number(r[i]))));
  const byWord = lower.match(/\bby\s+([a-z_]+)/)?.[1];
  const groupBy = columns.find((c) => c.toLowerCase() === byWord) ?? columns.find((c) => !numeric.includes(c) && !/date|time/i.test(c)) ?? columns[0];
  // Like a real model, the draft uses the word the user said — which may not be the exact column name.
  const value = columns.find((c) => lower.includes(c.toLowerCase()) && numeric.includes(c)) ?? VALUE_WORDS.find((w) => lower.includes(w)) ?? numeric.at(-1) ?? columns.at(-1)!;
  const code = `# proofbox:fixture=csv-analyze
import pandas as pd

GROUP_BY = "${groupBy}"
VALUE = "${value}"

df = pd.read_csv("/sandbox/input/data.csv")
print(f"loaded {len(df)} rows x {len(df.columns)} columns")
grouped = df.groupby(GROUP_BY)[VALUE].agg(["sum", "count", "mean"])
grouped = grouped.sort_values("sum", ascending=False)
grouped.to_csv("/sandbox/out/summary.csv")
print(grouped)`;
  return {
    intent: "csv",
    title: `Analyze data.csv — ${value} by ${groupBy}`,
    summary: `Mount the CSV read-only, write pandas code to aggregate ${value} by ${groupBy}, retry on errors, then prove the data cannot leave the sandbox.`,
    files: { "data.csv": csv },
    steps: [
      step(1, { kind: "code", language: "python", title: "Write + run analysis script", description: `Group by ${groupBy}, aggregate ${value}; emit summary table and chart data.`, code }),
    ],
  };
}

// ---------- browser ----------

function browserPlan(message: string): Omit<Plan, "id" | "createdAt" | "planner"> {
  const urls = [...message.matchAll(/https?:\/\/[^\s,)"']+/g)].map((m) => m[0].replace(/[.;:]$/, ""));
  const url = urls[0] ?? "https://docs.example.com/changelog";
  const hosts = [...new Set((urls.length ? urls : [url]).map((u) => new URL(u).hostname))];
  const expect = message.match(/evidence (?:of|for)\s+([^,.]+)/i)?.[1]?.trim() ?? "the main content";
  const wantsForm = /\bform\b|\bfill\b|\bsubmit\b|\bsign ?up\b/i.test(message);
  const fields = { "#name": "ProofBox Demo", "#email": "demo@proofbox.dev", "#message": "Interested in the Pro plan — drafted by the ProofBox agent." };
  const steps: PlanStep[] = [
    step(1, { kind: "browser", title: `Open ${new URL(url).hostname}`, description: "Headless browser inside the sandbox; egress only via the allowlist proxy.", browser: { action: "navigate", url } }),
    step(2, { kind: "browser", title: "Capture evidence", description: `Screenshot and DOM evidence for: ${expect}.`, browser: { action: "screenshot", url, expect } }),
  ];
  if (wantsForm) {
    steps.push(
      step(3, { kind: "browser", title: "Fill form as draft", description: "Type into the form fields; do not submit.", browser: { action: "fill", url, fields } }),
      step(4, { kind: "browser", title: "Submit form (final action)", description: "Side effect outside the read-only flow — requires a human yes/no.", browser: { action: "submit", url, fields }, requiresConfirm: true }),
    );
  }
  return {
    intent: "browser",
    title: `Research ${new URL(url).hostname} with receipts`,
    summary: `Browse inside the sandbox (requested hosts: ${hosts.join(", ")}; the server egress allowlist decides), capture evidence, verify it, and ${wantsForm ? "pause for your OK before submitting" : "never submit anything"}.`,
    egressAllowlist: hosts, // a request only — src/lib/policy.ts recomputes it
    steps,
  };
}

// ---------- helpers for explain/verify ----------

const lastLine = (s: string) => s.trim().split("\n").filter(Boolean).at(-1) ?? "";

function closestColumn(missing: string, columns: string[]): string | null {
  const m = missing.toLowerCase();
  return columns.find((c) => c.toLowerCase().includes(m) || m.includes(c.toLowerCase())) ?? columns.find((c) => c.toLowerCase().startsWith(m.slice(0, 3))) ?? null;
}

export class MockLlm implements LlmProvider {
  readonly name = "mock-llm (templates, no network)";

  async plan({ message }: PlanInput): Promise<Plan> {
    const intent = classifyIntent(message);
    const body = intent === "csv" ? csvPlan(message) : intent === "browser" ? browserPlan(message) : codePlan(message);
    return { id: newId("plan"), createdAt: now(), planner: this.name, ...body };
  }

  async repair(_step: PlanStep, code: string, receipt: Receipt, files: Record<string, string>): Promise<Repair | null> {
    const missing = receipt.stderr.match(/KeyError: '([^']+)'/)?.[1];
    if (missing && files["data.csv"]) {
      const { columns } = parseCsv(files["data.csv"]);
      const fix = closestColumn(missing, columns);
      if (!fix) return null;
      const fixed = code.replace(new RegExp(`(=\\s*)"${missing}"`, "g"), `$1"${fix}"`);
      return fixed === code ? null : { code: fixed, note: `Column '${missing}' does not exist; the closest match is '${fix}'. Retrying with the corrected column.` };
    }
    return null; // an AssertionError is a disproven claim, not a bug to paper over
  }

  async explain(step: PlanStep, r: Receipt): Promise<string> {
    const blocked = r.isolation.blockedAttempts;
    if (step.probe) {
      if (r.killedBy) return `Cap enforced: killed by the ${r.killedBy} limit (${r.limits.memoryMb} MiB / ${r.limits.timeoutMs} ms) inside ${r.sandboxId}. The host never saw the allocation.`;
      if (blocked.length) return `Containment held: ${blocked.length} escape attempt(s) blocked — ${blocked.join("; ")}. ${r.redactions} secret value(s) were redacted before entering the sandbox.`;
      return "Probe ran but nothing was blocked — review the policy.";
    }
    if (step.kind === "browser") {
      if (r.exitCode !== 0) return `Browser action failed: ${lastLine(r.stderr)}`;
      return `${lastLine(r.stdout)} — ${r.artifacts.filter((a) => a.kind === "image").length} screenshot(s) captured inside the sandbox.`;
    }
    if (r.exitCode === 0) {
      const proven = r.stdout.match(/assert .* ✓ proven/);
      return proven ? `Claim proven inside the sandbox (exit 0, ${r.durationMs} ms). Receipt sha256 ${r.sha256.slice(0, 12)}… lets anyone check the output was not edited.` : `Exit 0 in ${r.durationMs} ms. ${lastLine(r.stdout)}`;
    }
    if (/AssertionError/.test(r.stderr)) return `Claim disproven: ${lastLine(r.stderr)}. The receipt records the failure as-is.`;
    return `Exit ${r.exitCode}: ${lastLine(r.stderr)}`;
  }

  async verify(step: PlanStep, r: Receipt): Promise<{ ok: boolean; notes: string }> {
    if (step.probe) {
      const ok = r.isolation.blockedAttempts.length > 0 || Boolean(r.killedBy);
      return { ok, notes: ok ? "vision(mock): blocked page shown; request never left the sandbox." : "vision(mock): probe was NOT blocked." };
    }
    if (r.exitCode !== 0) return { ok: false, notes: `vision(mock): action failed — ${lastLine(r.stderr)}` };
    const ev = r.artifacts.find((a) => a.name === "dom-evidence.json");
    if (ev) {
      const hit = (JSON.parse(ev.content) as { highlighted: { label: string; text: string } | null }).highlighted;
      return hit
        ? { ok: true, notes: `vision(mock): screenshot shows "${hit.label}" card reading "${hit.text}"; matches "${step.browser?.expect}".` }
        : { ok: false, notes: "vision(mock): expected evidence not visible." };
    }
    if (step.browser?.action === "fill") return { ok: true, notes: "vision(mock): all fields filled, submit button untouched." };
    if (step.browser?.action === "submit") return { ok: true, notes: "vision(mock): confirmation banner visible; network log shows the POST was captured by the fixture." };
    return { ok: true, notes: "vision(mock): page rendered as expected." };
  }
}
